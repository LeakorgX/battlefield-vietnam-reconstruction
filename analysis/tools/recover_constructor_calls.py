"""Recover static-object initializers whose constructor takes immediate arguments.

Complements recover_static_initializers.py (which covers the argument-free form):

  push imm ... / mov ecx,object / call constructor /
  [push destructor_thunk / call atexit / pop ecx] / ret

The constructor is thiscall (it pops its own arguments). Pushes are read in
order, so the C argument list is the reverse of the push order; `push imm8` is
sign-extended. Objects without a registered destructor simply omit the atexit
call. The C replacement is not byte-identical; verify_static_initializers.py
checks ABI equivalence, including the exact constructor arguments.

Structural audit is the same as recover_field_accessors.py.
"""
import argparse
import csv
import hashlib
import json
import re
import struct
from pathlib import Path
import pefile
from recover_constant_returns import ROOT,HASHES
from recover_field_accessors import label_targets,absolute_pointers
from recover_static_initializers import ATEXIT

PATTERN=re.compile(rb'((?:\x6a.|\x68.{4})*)\xb9(.{4})\xe8(.{4})(?:\x68(.{4})\xe8(.{4})\x59)?\xc3',re.S)
PUSH=re.compile(rb'\x6a(.)|\x68(.{4})',re.S)

def parse(address,body):
    m=PATTERN.fullmatch(body)
    if not m:return None
    pushes=[struct.unpack('<b',p[0])[0]&0xffffffff if p[0] else struct.unpack('<I',p[1])[0]
            for p in PUSH.findall(m.group(1))]
    if not pushes:return None  # argument-free form belongs to static_initializers
    after_ctor=address+len(m.group(1))+10
    ctor=after_ctor+struct.unpack('<i',m.group(3))[0]
    dtor=atexit=None
    if m.group(4) is not None:
        dtor=struct.unpack('<I',m.group(4))[0];atexit=after_ctor+10+struct.unpack('<i',m.group(5))[0]
    return struct.unpack('<I',m.group(2))[0],ctor,pushes[::-1],dtor,atexit

def recover(game_dir,overwrite=False):
    destination=ROOT/'bfv-native-code/src/constructor_calls.c'
    if destination.exists() and not overwrite:raise RuntimeError('Source exists; --overwrite intentionally replaces edits.')
    source=['/* C++ static-object initializers whose constructor takes immediate arguments:',
            ' * construct the global object, then (when it has one) register its destructor',
            ' * thunk with the CRT atexit list. Constructors, destructors, argument meanings',
            ' * and object types remain native and unnamed.',
            ' * Generated by analysis/tools/recover_constructor_calls.py, then editable. */',
            '#include <stdint.h>','#include "target.h"',
            '#define TC __attribute__((thiscall))',
            'typedef int (*BfvAtexit)(void (*destructor)(void));','']
    catalog=dict(scope='C++ static-object initializers calling a constructor with immediate arguments, '
                 'optionally registering a destructor. Constructors, destructors and object types remain native.',targets={})
    registry=json.loads((ROOT/'reports/recovery-registry.json').read_text(encoding='utf-8'))
    taken={}
    for e in registry:
        for t,a in e['addresses'].items():taken.setdefault(t,set()).add(int(a,16))
    for target,(filename,digest) in HASHES.items():
        image=(game_dir/filename).read_bytes();assert hashlib.sha256(image).hexdigest()==digest
        pe=pefile.PE(data=image);base=pe.OPTIONAL_HEADER.ImageBase
        manifest=json.loads((ROOT/'bfv-native-code/build'/target/'manifest.json').read_text())
        patched=set()
        for p in manifest['entry_patches']:
            start=int(p['entry'],16);patched.update(range(start-4,start+len(p['original'])//2))
        candidates=[]
        with (ROOT/'reports'/target/'all-functions.tsv').open(encoding='utf-8') as f:
            for row in csv.DictReader(f,delimiter='\t'):
                address=int(row['address'],16);size=int(row['bytes'])
                if address in taken.get(target,()):continue
                body=pe.get_data(address-base,size);parsed=parse(address,body)
                if parsed:candidates.append((address,*parsed,body))
        labels=label_targets(ROOT/'bfv-native-code/build'/f'{target}-recomp')
        pointers=absolute_pointers(pe,image,min(c[0] for c in candidates),max(c[0] for c in candidates)+8)
        entries=[];rejected={};lines=['#if BFV_BUILD_'+target.upper(),
            f'#define BFV_ATEXIT ((BfvAtexit)0x{ATEXIT[target]:08x}u)','']
        for address,obj,ctor,arguments,dtor,atexit,body in sorted(candidates):
            interior=set(range(address+1,address+5));reason=None
            if address%16:reason='unaligned_entry'
            elif atexit is not None and atexit!=ATEXIT[target]:reason='other_registration_call'
            elif interior&patched or address in patched:reason='existing_patch'
            elif interior&labels:reason='interior_branch_target'
            elif interior&pointers:reason='interior_pointer'
            if reason:rejected[reason]=rejected.get(reason,0)+1;continue
            a=f'{address:08x}';symbol=f'bfv_{target}_construct_{a}'
            entries.append(dict(address=a,symbol=symbol,object=f'{obj:08x}',constructor=f'{ctor:08x}',
                arguments=[f'{x:08x}' for x in arguments],destructor=None if dtor is None else f'{dtor:08x}',
                guarded_prefix=body[:5].hex(),native_body=body.hex()))
            types=', '.join(['void *']+['uint32_t']*len(arguments))
            values=', '.join([f'(void *)0x{obj:08x}u']+[f'0x{x:08x}u' for x in arguments])
            note=f', destructor thunk {dtor:08x}' if dtor is not None else ', no registered destructor'
            lines+=[f'/* Native {a}; global object {obj:08x}, constructor {ctor:08x}{note}. */',
                f'void {symbol}(void)','{',
                f'    ((void (TC *)({types}))0x{ctor:08x}u)({values});']
            if dtor is not None:lines.append(f'    BFV_ATEXIT((void (*)(void))0x{dtor:08x}u);')
            lines+=['}','']
        source+=[*lines,'#undef BFV_ATEXIT','#endif','']
        catalog['targets'][target]=dict(original_sha256=digest,atexit=f'{ATEXIT[target]:08x}',rejected=rejected,entries=entries)
        print(target,len(entries),'with atexit',sum(bool(e['destructor']) for e in entries),'rejected',rejected)
    destination.write_text('\n'.join(source),encoding='utf-8',newline='\n')
    (ROOT/'bfv-native-code/constructor-calls.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--game-dir',type=Path,required=True)
    p.add_argument('--overwrite',action='store_true')
    a=p.parse_args();recover(a.game_dir,a.overwrite)
