"""Recover complete field/global accessor functions as editable C.

Each accepted function's whole body is one of a few exact instruction shapes
whose C translation compiles back to the same bytes (the verifier checks this):

  word_setter    mov eax,[esp+4] / mov [ecx+disp32],eax / ret 4
  float_getter   fld dword [ecx+disp32] / ret
  double_getter  fld qword [ecx+disp32] / ret
  field_address  lea eax,[ecx+disp32] / ret
  global_word    mov eax,[abs32] / ret
  byte_set_one   mov byte [ecx+disp32],1 / ret

Structural audit (no Ghidra needed): 16-byte aligned entry, the indexed body is
exactly the pattern, nothing is already detoured there, no branch label from
the static recompiler and no absolute pointer anywhere in the image targets the
first five bytes after the entry (the detour overwrites them).
"""
import argparse
import csv
import hashlib
import json
import re
import struct
from pathlib import Path
import pefile
from recover_constant_returns import ROOT,HASHES

PATTERNS={
    'word_setter':(re.compile(rb'\x8b\x44\x24\x04\x89\x81(.{4})\xc2\x04\x00',re.S),13),
    'float_getter':(re.compile(rb'\xd9\x81(.{4})\xc3',re.S),7),
    'double_getter':(re.compile(rb'\xdd\x81(.{4})\xc3',re.S),7),
    'field_address':(re.compile(rb'\x8d\x81(.{4})\xc3',re.S),7),
    'global_word':(re.compile(rb'\xa1(.{4})\xc3',re.S),6),
    'byte_set_one':(re.compile(rb'\xc6\x81(.{4})\x01\xc3',re.S),8),
}

def c_function(target,kind,address,value):
    a=f'{address:08x}';field=f'(const unsigned char *)object + {value}u'
    if kind=='word_setter':
        return (f'bfv_{target}_set_word_{a}',f'/* Native {a}; stores the argument to the object word at byte offset {value}. */',
            [f'void TC bfv_{target}_set_word_{a}(void *object, uint32_t value)','{',
             f'    ((volatile struct BfvWord *)((unsigned char *)object + {value}u))->value = value;','}'])
    if kind=='float_getter':
        return (f'bfv_{target}_read_float_{a}',f'/* Native {a}; object float at byte offset {value}. */',
            [f'float TC bfv_{target}_read_float_{a}(const void *object)','{',
             f'    return ((const volatile struct BfvFloat *)({field}))->value;','}'])
    if kind=='double_getter':
        return (f'bfv_{target}_read_double_{a}',f'/* Native {a}; object double at byte offset {value}. */',
            [f'double TC bfv_{target}_read_double_{a}(const void *object)','{',
             f'    return ((const volatile struct BfvDouble *)({field}))->value;','}'])
    if kind=='field_address':
        return (f'bfv_{target}_field_address_{a}',f'/* Native {a}; address of the object member at byte offset {value}. */',
            [f'void *TC bfv_{target}_field_address_{a}(void *object)','{',
             f'    return (unsigned char *)object + {value}u;','}'])
    if kind=='global_word':
        return (f'bfv_{target}_read_global_{a}',f'/* Native {a}; global word at {value:08x}. */',
            [f'uint32_t bfv_{target}_read_global_{a}(void)','{',
             f'    return ((const volatile struct BfvWord *)0x{value:08x}u)->value;','}'])
    if kind=='byte_set_one':
        return (f'bfv_{target}_set_byte_one_{a}',f'/* Native {a}; sets the object byte at byte offset {value} to 1. */',
            [f'void TC bfv_{target}_set_byte_one_{a}(void *object)','{',
             f'    ((volatile struct BfvByte *)((unsigned char *)object + {value}u))->value = 1;','}'])
    raise ValueError(kind)

def label_targets(recomp_dir):
    """Every branch/call target the static recompiler labelled."""
    labels=set()
    with (recomp_dir/'text.s').open(encoding='utf-8') as f:
        for line in f:
            if line[:4] in ('loc_','sub_') and line.rstrip().endswith(':'):labels.add(int(line[4:12],16))
    return labels

def absolute_pointers(pe,image,low,high):
    """Image dwords pointing into [low,high) at any byte alignment."""
    hits=set()
    for section in pe.sections:
        data=section.get_data()
        for n in range(len(data)-3):
            v=struct.unpack_from('<I',data,n)[0]
            if low<=v<high:hits.add(v)
    return hits

def recover(game_dir,overwrite=False):
    destination=ROOT/'bfv-native-code/src/field_accessors.c'
    if destination.exists() and not overwrite:raise RuntimeError('Source exists; --overwrite intentionally replaces edits.')
    source=['/* Complete ECX object-field and global accessors: setters, float/double getters,',
            ' * member addresses and global reads. Field meanings and owning classes remain',
            ' * unproven. Packed volatile accesses keep the native single unaligned access.',
            ' * Generated by analysis/tools/recover_field_accessors.py, then editable. */',
            '#include <stdint.h>','#include "target.h"',
            'struct __attribute__((packed)) BfvWord { uint32_t value; };',
            'struct __attribute__((packed)) BfvByte { uint8_t value; };',
            'struct __attribute__((packed)) BfvFloat { float value; };',
            'struct __attribute__((packed)) BfvDouble { double value; };',
            '#define TC __attribute__((thiscall))','']
    catalog=dict(scope='Complete thiscall field setters/getters/member addresses and cdecl global reads. '
                 'Object ownership and semantic field types remain unresolved.',targets={})
    registry=json.loads((ROOT/'reports/recovery-registry.json').read_text(encoding='utf-8'))
    taken={}
    for e in registry:
        for t,a in e['addresses'].items():taken.setdefault(t,set()).add(int(a,16))
    for target,(filename,digest) in HASHES.items():
        image=(game_dir/filename).read_bytes();assert hashlib.sha256(image).hexdigest()==digest
        pe=pefile.PE(data=image);base=pe.OPTIONAL_HEADER.ImageBase
        manifest=json.loads((ROOT/'bfv-native-code/build'/target/'manifest.json').read_text())
        patched=set()
        for p in manifest['entry_patches']:
            start=int(p['entry'],16);patched.update(range(start-4,start+len(p['original'])//2))
        candidates=[]
        with (ROOT/'reports'/target/'all-functions.tsv').open(encoding='utf-8') as f:
            for row in csv.DictReader(f,delimiter='\t'):
                address=int(row['address'],16);size=int(row['bytes'])
                if address in taken.get(target,()):continue
                body=pe.get_data(address-base,size)
                for kind,(pattern,length) in PATTERNS.items():
                    m=pattern.fullmatch(body)
                    if m and size==length:candidates.append((address,kind,struct.unpack('<I',m.group(1))[0],body));break
        labels=label_targets(ROOT/'bfv-native-code/build'/f'{target}-recomp')
        low=min(c[0] for c in candidates);high=max(c[0] for c in candidates)+8
        pointers=absolute_pointers(pe,image,low,high)
        entries=[];rejected={};body_lines=['#if BFV_BUILD_'+target.upper()]
        for address,kind,value,body in sorted(candidates):
            interior=set(range(address+1,address+5))
            reason=None
            if address%16:reason='unaligned_entry'
            elif kind!='global_word' and not 128<=value<=0x7fffffff:reason='short_or_negative_offset'
            elif interior&patched or address in patched:reason='existing_patch'
            elif interior&labels:reason='interior_branch_target'
            elif interior&pointers:reason='interior_pointer'
            if reason:rejected[reason]=rejected.get(reason,0)+1;continue
            symbol,comment,lines=c_function(target,kind,address,value)
            entries.append(dict(address=f'{address:08x}',symbol=symbol,kind=kind,
                **({'global_address':f'{value:08x}'} if kind=='global_word' else {'field_offset':value}),
                guarded_prefix=body[:5].hex(),native_body=body.hex()))
            body_lines+=[comment,*lines,'']
        source+=[*body_lines,'#endif','']
        counts={}
        for e in entries:counts[e['kind']]=counts.get(e['kind'],0)+1
        catalog['targets'][target]=dict(original_sha256=digest,counts=counts,rejected=rejected,entries=entries)
        print(target,len(entries),counts,'rejected',rejected)
    destination.write_text('\n'.join(source),encoding='utf-8',newline='\n')
    (ROOT/'bfv-native-code/field-accessors.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--game-dir',type=Path,required=True)
    p.add_argument('--overwrite',action='store_true')
    a=p.parse_args();recover(a.game_dir,a.overwrite)
