"""Recover MSVC scalar deleting destructors as editable C.

MSVC gives every polymorphic class a `scalar deleting destructor`: the virtual
destructor slot that destroys the object and, when bit 0 of its argument is
set, frees it. Three exact shapes are accepted:

  destroy        push esi / mov esi,ecx / call destructor /
                 test byte [esp+8],1 / je L / push esi / call deallocate / add esp,4 /
              L: mov eax,esi / pop esi / ret 4
  vtable         same, but the (trivial, inlined) destructor only stores the vtable
  vtable_destroy stores the vtable, then calls the base destructor

The C replacement performs the same store and calls. It is not byte-identical:
GCC chooses its own registers and frame. The verifier checks ABI equivalence.
Every accepted body frees through the same shared deallocator (client
`00403680`, server `00403df0`); its identity as `operator delete` is not proven.

Structural audit is the same as recover_field_accessors.py. Ghidra's indexed
size stops before the final `ret 4`; the next indexed function must begin at or
after the real end.
"""
import argparse
import csv
import hashlib
import json
import re
import struct
from pathlib import Path
import pefile
from recover_constant_returns import ROOT,HASHES
from recover_field_accessors import label_targets,absolute_pointers

TAIL=rb'\x74\x09\x56\xe8(.{4})\x83\xc4\x04\x8b\xc6\x5e\xc2\x04\x00'
SHAPES={
    'destroy':re.compile(rb'\x56\x8b\xf1\xe8(.{4})\xf6\x44\x24\x08\x01'+TAIL,re.S),
    'vtable':re.compile(rb'\xf6\x44\x24\x04\x01\x56\x8b\xf1\xc7\x06(.{4})'+TAIL,re.S),
    'vtable_destroy':re.compile(rb'\x56\x8b\xf1\xc7\x06(.{4})\xe8(.{4})\xf6\x44\x24\x08\x01'+TAIL,re.S),
}
DEALLOCATE={'client':0x00403680,'server':0x00403df0}

def decode(kind,address,m):
    """(vtable, destructor, deallocator) with absent members as None."""
    end=address+m.end()
    deallocate=end-9+struct.unpack('<i',m.group(m.lastindex))[0]
    if kind=='destroy':return None,address+8+struct.unpack('<i',m.group(1))[0],deallocate
    if kind=='vtable':return struct.unpack('<I',m.group(1))[0],None,deallocate
    return struct.unpack('<I',m.group(1))[0],address+14+struct.unpack('<i',m.group(2))[0],deallocate

def recover(game_dir,overwrite=False):
    destination=ROOT/'bfv-native-code/src/deleting_destructors.c'
    if destination.exists() and not overwrite:raise RuntimeError('Source exists; --overwrite intentionally replaces edits.')
    source=['/* MSVC scalar deleting destructors: optionally store the class vtable, run the',
            ' * destructor, free the object when bit 0 of the flags is set, return the object.',
            ' * Destructors, the shared deallocator and class identities remain native/unnamed.',
            ' * Generated by analysis/tools/recover_deleting_destructors.py, then editable. */',
            '#include <stdint.h>','#include "target.h"',
            '#define TC __attribute__((thiscall))',
            'typedef void (TC *BfvDestructor)(void *object);',
            'typedef void (*BfvDeallocate)(void *object);',
            'struct __attribute__((packed)) BfvVtableSlot { uint32_t value; };','']
    catalog=dict(scope='MSVC scalar deleting destructors (vtable store, destructor call, conditional free). '
                 'Destructors, the deallocator and class identities remain native.',targets={})
    registry=json.loads((ROOT/'reports/recovery-registry.json').read_text(encoding='utf-8'))
    taken={}
    for e in registry:
        for t,a in e['addresses'].items():taken.setdefault(t,set()).add(int(a,16))
    for target,(filename,digest) in HASHES.items():
        image=(game_dir/filename).read_bytes();assert hashlib.sha256(image).hexdigest()==digest
        pe=pefile.PE(data=image);base=pe.OPTIONAL_HEADER.ImageBase
        manifest=json.loads((ROOT/'bfv-native-code/build'/target/'manifest.json').read_text())
        patched=set()
        for p in manifest['entry_patches']:
            start=int(p['entry'],16);patched.update(range(start-4,start+len(p['original'])//2))
        with (ROOT/'reports'/target/'all-functions.tsv').open(encoding='utf-8') as f:
            rows=[(int(r['address'],16),int(r['bytes'])) for r in csv.DictReader(f,delimiter='\t')]
        starts=sorted(a for a,_ in rows);following={a:b for a,b in zip(starts,starts[1:]+[1<<32])}
        candidates=[]
        for address,size in rows:
            if address in taken.get(target,()):continue
            body=pe.get_data(address-base,40)
            for kind,pattern in SHAPES.items():
                m=pattern.match(body)
                if m and size==m.end()-3:candidates.append((address,kind,m.end(),decode(kind,address,m),body[:m.end()]));break
        labels=label_targets(ROOT/'bfv-native-code/build'/f'{target}-recomp')
        pointers=absolute_pointers(pe,image,min(c[0] for c in candidates),max(c[0] for c in candidates)+8)
        entries=[];rejected={};lines=['#if BFV_BUILD_'+target.upper(),
            f'#define BFV_DEALLOCATE ((BfvDeallocate)0x{DEALLOCATE[target]:08x}u)','']
        for address,kind,length,(vtable,destructor,deallocate),body in sorted(candidates):
            interior=set(range(address+1,address+5));reason=None
            if address%16:reason='unaligned_entry'
            elif deallocate!=DEALLOCATE[target]:reason='other_deallocator'
            elif following[address]<address+length:reason='overlapping_function'
            elif interior&patched or address in patched:reason='existing_patch'
            elif interior&labels:reason='interior_branch_target'
            elif interior&pointers:reason='interior_pointer'
            if reason:rejected[reason]=rejected.get(reason,0)+1;continue
            a=f'{address:08x}';symbol=f'bfv_{target}_deleting_destructor_{a}'
            entries.append(dict(address=a,symbol=symbol,kind=kind,
                vtable=None if vtable is None else f'{vtable:08x}',
                destructor=None if destructor is None else f'{destructor:08x}',
                guarded_prefix=body[:5].hex(),native_body=body.hex()))
            parts=[]
            if vtable is not None:parts.append(f'vtable {vtable:08x}')
            if destructor is not None:parts.append(f'destructor {destructor:08x}')
            lines+=[f'/* Native {a}; {", ".join(parts)}. */',
                f'void *TC {symbol}(void *object, uint32_t flags)','{']
            if vtable is not None:lines.append(f'    ((volatile struct BfvVtableSlot *)object)->value = 0x{vtable:08x}u;')
            if destructor is not None:lines.append(f'    ((BfvDestructor)0x{destructor:08x}u)(object);')
            lines+=['    if (flags & 1u)','        BFV_DEALLOCATE(object);','    return object;','}','']
        source+=[*lines,'#undef BFV_DEALLOCATE','#endif','']
        counts={}
        for e in entries:counts[e['kind']]=counts.get(e['kind'],0)+1
        catalog['targets'][target]=dict(original_sha256=digest,deallocate=f'{DEALLOCATE[target]:08x}',
            counts=counts,rejected=rejected,entries=entries)
        print(target,len(entries),counts,'rejected',rejected)
    destination.write_text('\n'.join(source),encoding='utf-8',newline='\n')
    (ROOT/'bfv-native-code/deleting-destructors.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--game-dir',type=Path,required=True)
    p.add_argument('--overwrite',action='store_true')
    a=p.parse_args();recover(a.game_dir,a.overwrite)
