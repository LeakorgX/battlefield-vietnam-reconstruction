"""Recover small virtual clone functions (`return new T(*this)`) as editable C.

  push esi / push size / mov esi,ecx / call allocate / add esp,4 /
  test eax,eax / je null /
  (mov reg,[esi+d8] / mov [eax+d8],reg)* / mov dword [eax],vtable / pop esi / ret
  null: xor eax,eax / pop esi / ret

The allocation routine is the same for every accepted body (client `00403610`,
server `00403d80`); that it is `operator new` is likely but not proven, so it is
named `BFV_ALLOCATE`. Copied fields are word copies in native order, followed
by the vtable store. The C replacement is not byte-identical;
verify_clones.py checks ABI equivalence. Structural audit is the same as
recover_field_accessors.py.
"""
import argparse
import csv
import hashlib
import json
import re
import struct
from pathlib import Path
import pefile
from recover_constant_returns import ROOT,HASHES
from recover_field_accessors import label_targets,absolute_pointers

PATTERN=re.compile(rb'\x56(\x6a.|\x68.{4})\x8b\xf1\xe8(.{4})\x83\xc4\x04\x85\xc0\x74(.)'
                   rb'((?:\x8b\x4e.\x89\x48.|\x8b\x56.\x89\x50.)*)\xc7\x00(.{4})\x5e\xc3\x33\xc0\x5e\xc3',re.S)
ALLOCATE={'client':0x00403610,'server':0x00403d80}

def parse(address,body):
    m=PATTERN.fullmatch(body)
    if not m:return None
    push=m.group(1);size=push[1] if len(push)==2 else struct.unpack('<I',push[1:])[0]
    allocate=address+1+len(push)+2+5+struct.unpack('<i',m.group(2))[0]
    copies=m.group(4);fields=[(copies[i+2],copies[i+5]) for i in range(0,len(copies),6)]
    null_target=address+m.start(3)+1+m.group(3)[0]
    if null_target!=address+len(body)-4:return None
    return size,allocate,fields,struct.unpack('<I',m.group(5))[0]

def recover(game_dir,overwrite=False):
    destination=ROOT/'bfv-native-code/src/clones.c'
    if destination.exists() and not overwrite:raise RuntimeError('Source exists; --overwrite intentionally replaces edits.')
    source=['/* Virtual clone functions (`return new T(*this)`) for small classes: allocate,',
            ' * copy the data words, store the class vtable. Allocation routine, vtables and',
            ' * class identities remain native/unnamed.',
            ' * Generated by analysis/tools/recover_clones.py, then editable. */',
            '#include <stdint.h>','#include "target.h"',
            '#define TC __attribute__((thiscall))',
            'typedef void *(*BfvAllocate)(uint32_t size);',
            'struct __attribute__((packed)) BfvWord { uint32_t value; };',
            '#define BFV_WORD(base, offset) (((volatile struct BfvWord *)((unsigned char *)(base) + (offset)))->value)','']
    catalog=dict(scope='Virtual clone functions: allocate, copy data words, store vtable. '
                 'The allocation routine and class identities remain native.',targets={})
    registry=json.loads((ROOT/'reports/recovery-registry.json').read_text(encoding='utf-8'))
    taken={}
    for e in registry:
        for t,a in e['addresses'].items():taken.setdefault(t,set()).add(int(a,16))
    for target,(filename,digest) in HASHES.items():
        image=(game_dir/filename).read_bytes();assert hashlib.sha256(image).hexdigest()==digest
        pe=pefile.PE(data=image);base=pe.OPTIONAL_HEADER.ImageBase
        manifest=json.loads((ROOT/'bfv-native-code/build'/target/'manifest.json').read_text())
        patched=set()
        for p in manifest['entry_patches']:
            start=int(p['entry'],16);patched.update(range(start-4,start+len(p['original'])//2))
        candidates=[]
        with (ROOT/'reports'/target/'all-functions.tsv').open(encoding='utf-8') as f:
            for row in csv.DictReader(f,delimiter='\t'):
                address=int(row['address'],16);size=int(row['bytes'])
                if address in taken.get(target,()):continue
                body=pe.get_data(address-base,size);parsed=parse(address,body)
                if parsed:candidates.append((address,*parsed,body))
        labels=label_targets(ROOT/'bfv-native-code/build'/f'{target}-recomp')
        pointers=absolute_pointers(pe,image,min(c[0] for c in candidates),max(c[0] for c in candidates)+8)
        entries=[];rejected={};lines=['#if BFV_BUILD_'+target.upper(),
            f'#define BFV_ALLOCATE ((BfvAllocate)0x{ALLOCATE[target]:08x}u)','']
        for address,size,allocate,fields,vtable,body in sorted(candidates):
            interior=set(range(address+1,address+5));reason=None
            if address%16:reason='unaligned_entry'
            elif allocate!=ALLOCATE[target]:reason='other_allocator'
            elif any(s>=0x80 or d>=0x80 or s%4 or d%4 or d+4>size or d==0 for s,d in fields):reason='unusual_field'
            elif interior&patched or address in patched:reason='existing_patch'
            elif interior&labels:reason='interior_branch_target'
            elif interior&pointers:reason='interior_pointer'
            if reason:rejected[reason]=rejected.get(reason,0)+1;continue
            a=f'{address:08x}';symbol=f'bfv_{target}_clone_{a}'
            entries.append(dict(address=a,symbol=symbol,size=size,fields=[[s,d] for s,d in fields],
                vtable=f'{vtable:08x}',guarded_prefix=body[:5].hex(),native_body=body.hex()))
            lines+=[f'/* Native {a}; {size}-byte object, vtable {vtable:08x}. */',
                f'void *TC {symbol}(const void *self)','{',
                f'    void *copy = BFV_ALLOCATE({size}u);',
                '    if (!copy)','        return 0;',
                *[f'    BFV_WORD(copy, {d}u) = BFV_WORD(self, {s}u);' for s,d in fields],
                f'    BFV_WORD(copy, 0u) = 0x{vtable:08x}u;','    return copy;','}','']
        source+=[*lines,'#undef BFV_ALLOCATE','#endif','']
        catalog['targets'][target]=dict(original_sha256=digest,allocate=f'{ALLOCATE[target]:08x}',rejected=rejected,entries=entries)
        print(target,len(entries),'rejected',rejected)
    destination.write_text('\n'.join(source),encoding='utf-8',newline='\n')
    (ROOT/'bfv-native-code/clones.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--game-dir',type=Path,required=True)
    p.add_argument('--overwrite',action='store_true')
    a=p.parse_args();recover(a.game_dir,a.overwrite)
