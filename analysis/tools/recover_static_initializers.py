"""Recover C++ static-object initializers as editable C.

MSVC emits one initializer per global object with a constructor and destructor
(`static Foo g_foo;`). The CRT calls each through its initializer table:

  mov ecx,object / call constructor / push destructor_thunk / call atexit / pop ecx / ret

The C replacement makes the same two calls with the same arguments. It is not
byte-identical: GCC keeps a 16-byte-aligned frame and calls through EAX. Only
registers the calling convention leaves scratch (EAX before the calls, ECX,
EDX, flags) may differ; the verifier checks everything else.

Structural audit is the same as recover_field_accessors.py.
"""
import argparse
import csv
import hashlib
import json
import re
import struct
from pathlib import Path
import pefile
from recover_constant_returns import ROOT,HASHES
from recover_field_accessors import label_targets,absolute_pointers

PATTERN=re.compile(rb'\xb9(.{4})\xe8(.{4})\x68(.{4})\xe8(.{4})\x59\xc3',re.S)
ATEXIT={'client':0x007c2cd2,'server':0x0063b363}

def recover(game_dir,overwrite=False):
    destination=ROOT/'bfv-native-code/src/static_initializers.c'
    if destination.exists() and not overwrite:raise RuntimeError('Source exists; --overwrite intentionally replaces edits.')
    source=['/* C++ static-object initializers: construct the global object, then register',
            ' * its destructor thunk with the CRT atexit list. Constructors, destructors and',
            ' * object types remain native and unnamed.',
            ' * Generated by analysis/tools/recover_static_initializers.py, then editable. */',
            '#include <stdint.h>','#include "target.h"',
            '#define TC __attribute__((thiscall))',
            'typedef void (TC *BfvConstructor)(void *object);',
            'typedef int (*BfvAtexit)(void (*destructor)(void));','']
    catalog=dict(scope='C++ static-object initializers (constructor call plus atexit registration). '
                 'Constructors, destructors and object types remain native.',targets={})
    registry=json.loads((ROOT/'reports/recovery-registry.json').read_text(encoding='utf-8'))
    taken={}
    for e in registry:
        for t,a in e['addresses'].items():taken.setdefault(t,set()).add(int(a,16))
    for target,(filename,digest) in HASHES.items():
        image=(game_dir/filename).read_bytes();assert hashlib.sha256(image).hexdigest()==digest
        pe=pefile.PE(data=image);base=pe.OPTIONAL_HEADER.ImageBase
        manifest=json.loads((ROOT/'bfv-native-code/build'/target/'manifest.json').read_text())
        patched=set()
        for p in manifest['entry_patches']:
            start=int(p['entry'],16);patched.update(range(start-4,start+len(p['original'])//2))
        candidates=[]
        with (ROOT/'reports'/target/'all-functions.tsv').open(encoding='utf-8') as f:
            for row in csv.DictReader(f,delimiter='\t'):
                address=int(row['address'],16);size=int(row['bytes'])
                if size!=22 or address in taken.get(target,()):continue
                body=pe.get_data(address-base,size);m=PATTERN.fullmatch(body)
                if not m:continue
                obj,ctor,dtor,at=struct.unpack('<IiIi',m.group(1)+m.group(2)+m.group(3)+m.group(4))
                candidates.append((address,obj,address+10+ctor,dtor,address+20+at,body))
        labels=label_targets(ROOT/'bfv-native-code/build'/f'{target}-recomp')
        pointers=absolute_pointers(pe,image,min(c[0] for c in candidates),max(c[0] for c in candidates)+8)
        entries=[];rejected={};lines=['#if BFV_BUILD_'+target.upper(),
            f'#define BFV_ATEXIT ((BfvAtexit)0x{ATEXIT[target]:08x}u)','']
        for address,obj,ctor,dtor,atexit,body in sorted(candidates):
            interior=set(range(address+1,address+5));reason=None
            if address%16:reason='unaligned_entry'
            elif atexit!=ATEXIT[target]:reason='other_registration_call'
            elif interior&patched or address in patched:reason='existing_patch'
            elif interior&labels:reason='interior_branch_target'
            elif interior&pointers:reason='interior_pointer'
            if reason:rejected[reason]=rejected.get(reason,0)+1;continue
            a=f'{address:08x}';symbol=f'bfv_{target}_static_init_{a}'
            entries.append(dict(address=a,symbol=symbol,object=f'{obj:08x}',constructor=f'{ctor:08x}',
                destructor=f'{dtor:08x}',guarded_prefix=body[:5].hex(),native_body=body.hex()))
            lines+=[f'/* Native {a}; global object {obj:08x}, constructor {ctor:08x}, destructor thunk {dtor:08x}. */',
                f'void {symbol}(void)','{',
                f'    ((BfvConstructor)0x{ctor:08x}u)((void *)0x{obj:08x}u);',
                f'    BFV_ATEXIT((void (*)(void))0x{dtor:08x}u);','}','']
        source+=[*lines,'#undef BFV_ATEXIT','#endif','']
        catalog['targets'][target]=dict(original_sha256=digest,atexit=f'{ATEXIT[target]:08x}',rejected=rejected,entries=entries)
        print(target,len(entries),'rejected',rejected)
    destination.write_text('\n'.join(source),encoding='utf-8',newline='\n')
    (ROOT/'bfv-native-code/static-initializers.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--game-dir',type=Path,required=True)
    p.add_argument('--overwrite',action='store_true')
    a=p.parse_args();recover(a.game_dir,a.overwrite)
