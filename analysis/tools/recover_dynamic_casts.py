"""Recover small dynamic_cast wrappers as editable C.

Both shapes call the MSVC runtime cast `__RTDynamicCast(object, 0, &source_type,
&target_type, 0)` (client `007c334d`, server `0063cbf8`). The two pushed
constants are verified to be RTTI TypeDescriptors (type_info vtable, spare word,
then a decorated `.?A...` name), which names the classes involved.

  holder  mov eax,[esp+4] / mov eax,[eax] / <cast eax> / ret 4
          returns dynamic_cast of the pointer stored at the argument; ECX unused.
  handle  mov eax,[ecx] / test eax,eax / jne / ret /
          mov dl,[ecx+d8] / test dl,dl / je done / <cast eax> / done: ret
          returns 0 for an empty handle, the raw pointer when the handle's
          flag byte is clear, otherwise the dynamic_cast result.
  handle_arg  the same with the handle passed on the stack (`mov ecx,[esp+4]`,
          `ret 4`); ECX unused.
  pointer mov eax,[esp+4] / <cast eax> / ret 4: casts the argument; ECX unused.
  self    <cast ecx> / ret: casts `this`.

The C replacement is not byte-identical; verify_dynamic_casts.py checks ABI
equivalence. Structural audit is the same as recover_field_accessors.py.
"""
import argparse
import csv
import hashlib
import json
import re
import struct
from pathlib import Path
import pefile
from recover_constant_returns import ROOT,HASHES
from recover_field_accessors import label_targets,absolute_pointers

CALL=rb'\x6a\x00\x68(.{4})\x68(.{4})\x6a\x00\x50\xe8(.{4})\x83\xc4\x14'
SHAPES={
    'holder':re.compile(rb'\x8b\x44\x24\x04\x8b\x00'+CALL+rb'\xc2\x04\x00',re.S),
    'handle':re.compile(rb'\x8b\x01\x85\xc0\x75\x01\xc3\x8a\x51(.)\x84\xd2\x74\x17'+CALL+rb'\xc3',re.S),
    'handle_arg':re.compile(rb'\x8b\x4c\x24\x04\x8b\x01\x85\xc0\x75\x03\xc2\x04\x00\x8a\x51(.)\x84\xd2\x74\x17'
                            +CALL+rb'\xc2\x04\x00',re.S),
    'pointer':re.compile(rb'\x8b\x44\x24\x04'+CALL+rb'\xc2\x04\x00',re.S),
    'self':re.compile(CALL.replace(rb'\x50\xe8',rb'\x51\xe8')+rb'\xc3',re.S),
}
DYNAMIC_CAST={'client':0x007c334d,'server':0x0063cbf8}

def type_name(pe,base,address):
    """Decorated RTTI name of a TypeDescriptor, or None if it is not one."""
    try:data=pe.get_data(address-base,256)
    except Exception:return None
    name=data[8:].split(b'\0')[0]
    if struct.unpack_from('<I',data,4)[0] or not name.startswith(b'.?A') or not name.endswith(b'@@'):return None
    return name.decode('ascii')

def readable(name):
    """`.?AVGMObject@bf@dice@@` -> `dice::bf::GMObject`; templates stay decorated."""
    body=name[4:-2]
    if '?' in body or '$' in body:return name
    return '::'.join(reversed(body.split('@')))

def recover(game_dir,overwrite=False):
    destination=ROOT/'bfv-native-code/src/dynamic_casts.c'
    if destination.exists() and not overwrite:raise RuntimeError('Source exists; --overwrite intentionally replaces edits.')
    source=['/* dynamic_cast wrappers around the MSVC runtime __RTDynamicCast. Source and',
            ' * target classes come from the RTTI TypeDescriptors passed to the cast.',
            ' * Generated by analysis/tools/recover_dynamic_casts.py, then editable. */',
            '#include <stdint.h>','#include "target.h"',
            '#define TC __attribute__((thiscall))',
            'typedef void *(*BfvDynamicCast)(void *object, int32_t vfdelta, const void *source_type,',
            '                                const void *target_type, int32_t is_reference);',
            'struct __attribute__((packed)) BfvPointer { void *value; };',
            'struct __attribute__((packed)) BfvFlag { uint8_t value; };','']
    catalog=dict(scope='dynamic_cast wrappers (pointer holder, flagged handle, direct pointer and this). The runtime cast and '
                 'class layouts remain native.',targets={})
    registry=json.loads((ROOT/'reports/recovery-registry.json').read_text(encoding='utf-8'))
    taken={}
    for e in registry:
        if e['source']=='bfv-native-code/src/dynamic_casts.c':continue  # regenerate this family
        for t,a in e['addresses'].items():taken.setdefault(t,set()).add(int(a,16))
    for target,(filename,digest) in HASHES.items():
        image=(game_dir/filename).read_bytes();assert hashlib.sha256(image).hexdigest()==digest
        pe=pefile.PE(data=image);base=pe.OPTIONAL_HEADER.ImageBase
        manifest=json.loads((ROOT/'bfv-native-code/build'/target/'manifest.json').read_text())
        previous=ROOT/'bfv-native-code/dynamic-casts.json'
        own=set()
        if previous.exists():
            own={int(e['address'],16) for e in json.loads(previous.read_text())['targets'].get(target,{}).get('entries',[])}
        patched=set()
        for p in manifest['entry_patches']:
            start=int(p['entry'],16)
            if start not in own:patched.update(range(start-4,start+len(p['original'])//2))
        candidates=[]
        with (ROOT/'reports'/target/'all-functions.tsv').open(encoding='utf-8') as f:
            for row in csv.DictReader(f,delimiter='\t'):
                address=int(row['address'],16);size=int(row['bytes'])
                if address in taken.get(target,()):continue
                body=pe.get_data(address-base,size)
                for kind,pattern in SHAPES.items():
                    m=pattern.fullmatch(body)
                    if not m:continue
                    flag=m.group(1)[0] if kind.startswith('handle') else None
                    g=m.lastindex;dst,src=struct.unpack('<II',m.group(g-2)+m.group(g-1))
                    cast=address+m.end(g)+struct.unpack('<i',m.group(g))[0]
                    candidates.append((address,kind,flag,src,dst,cast,body));break
        labels=label_targets(ROOT/'bfv-native-code/build'/f'{target}-recomp')
        pointers=absolute_pointers(pe,image,min(c[0] for c in candidates),max(c[0] for c in candidates)+8)
        entries=[];rejected={};lines=['#if BFV_BUILD_'+target.upper(),
            f'#define BFV_DYNAMIC_CAST ((BfvDynamicCast)0x{DYNAMIC_CAST[target]:08x}u)','']
        for address,kind,flag,src,dst,cast,body in sorted(candidates):
            interior=set(range(address+1,address+5));reason=None
            source_name,target_name=type_name(pe,base,src),type_name(pe,base,dst)
            if address%16:reason='unaligned_entry'
            elif cast!=DYNAMIC_CAST[target]:reason='other_cast_routine'
            elif not source_name or not target_name:reason='not_type_descriptor'
            elif interior&patched or address in patched:reason='existing_patch'
            elif interior&labels:reason='interior_branch_target'
            elif interior&pointers:reason='interior_pointer'
            if reason:rejected[reason]=rejected.get(reason,0)+1;continue
            a=f'{address:08x}';symbol=f'bfv_{target}_dynamic_cast_{a}'
            entries.append(dict(address=a,symbol=symbol,kind=kind,flag_offset=flag,
                source_type=f'{src:08x}',target_type=f'{dst:08x}',source_name=source_name,target_name=target_name,
                guarded_prefix=body[:5].hex(),native_body=body.hex()))
            cast_call=f'BFV_DYNAMIC_CAST(object, 0, (const void *)0x{src:08x}u, (const void *)0x{dst:08x}u, 0)'
            lines.append(f'/* Native {a}; {readable(source_name)} -> {readable(target_name)}. */')
            if kind=='holder':
                lines+=[f'void *TC {symbol}(void *unused_ecx, void *const *holder)','{','    void *object = *holder;',
                    '    (void)unused_ecx;',f'    return {cast_call};','}','']
            elif kind=='pointer':
                lines+=[f'void *TC {symbol}(void *unused_ecx, void *object)','{','    (void)unused_ecx;',
                    f'    return {cast_call};','}','']
            elif kind=='self':
                lines+=[f'void *TC {symbol}(void *object)','{',f'    return {cast_call};','}','']
            elif kind=='handle_arg':
                lines+=[f'void *TC {symbol}(void *unused_ecx, const void *handle)','{','    (void)unused_ecx;',
                    '    void *object = ((const volatile struct BfvPointer *)handle)->value;',
                    f'    if (!object || !((const volatile struct BfvFlag *)((const unsigned char *)handle + {flag}u))->value)',
                    '        return object;',f'    return {cast_call};','}','']
            else:
                lines+=[f'void *TC {symbol}(const void *handle)','{',
                    '    void *object = ((const volatile struct BfvPointer *)handle)->value;',
                    f'    if (!object || !((const volatile struct BfvFlag *)((const unsigned char *)handle + {flag}u))->value)',
                    '        return object;',f'    return {cast_call};','}','']
        source+=[*lines,'#undef BFV_DYNAMIC_CAST','#endif','']
        counts={}
        for e in entries:counts[e['kind']]=counts.get(e['kind'],0)+1
        catalog['targets'][target]=dict(original_sha256=digest,dynamic_cast=f'{DYNAMIC_CAST[target]:08x}',
            counts=counts,rejected=rejected,entries=entries)
        print(target,len(entries),counts,'rejected',rejected)
    destination.write_text('\n'.join(source),encoding='utf-8',newline='\n')
    (ROOT/'bfv-native-code/dynamic-casts.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--game-dir',type=Path,required=True)
    p.add_argument('--overwrite',action='store_true')
    a=p.parse_args();recover(a.game_dir,a.overwrite)
