"""Recover constant global-store functions as editable C.

  (mov dword [global],imm32 | mov byte [global],imm8)+ / ret

Almost all are C++ static-object initializers that store a vtable (or a
self-pointer / flag) into a global object whose constructor was inlined. Stores
keep their native order and width. The C replacement is expected to compile to
the same instructions, but verify_global_stores.py checks behaviour, not bytes.
Structural audit is the same as recover_field_accessors.py.
"""
import argparse
import csv
import hashlib
import json
import re
import struct
from pathlib import Path
import pefile
from recover_constant_returns import ROOT,HASHES
from recover_field_accessors import label_targets,absolute_pointers

PATTERN=re.compile(rb'((?:\xc7\x05.{8}|\xc6\x05.{5})+)\xc3',re.S)
STORE=re.compile(rb'\xc7\x05(.{4})(.{4})|\xc6\x05(.{4})(.)',re.S)

def parse(body):
    m=PATTERN.fullmatch(body)
    if not m:return None
    stores=[]
    for s in STORE.finditer(m.group(1)):
        if s.group(1) is not None:stores.append((struct.unpack('<I',s.group(1))[0],4,struct.unpack('<I',s.group(2))[0]))
        else:stores.append((struct.unpack('<I',s.group(3))[0],1,s.group(4)[0]))
    return stores

def recover(game_dir,overwrite=False):
    destination=ROOT/'bfv-native-code/src/global_stores.c'
    if destination.exists() and not overwrite:raise RuntimeError('Source exists; --overwrite intentionally replaces edits.')
    source=['/* Constant global stores, mostly static-object initializers whose constructor',
            ' * was inlined down to a vtable or self-pointer store. Object types remain',
            ' * native and unnamed. Packed volatile accesses keep native order and width.',
            ' * Generated by analysis/tools/recover_global_stores.py, then editable. */',
            '#include <stdint.h>','#include "target.h"',
            'struct __attribute__((packed)) BfvWord { uint32_t value; };',
            'struct __attribute__((packed)) BfvByte { uint8_t value; };','']
    catalog=dict(scope='Functions that only store constants into globals, then return. '
                 'Object types and meanings remain native.',targets={})
    registry=json.loads((ROOT/'reports/recovery-registry.json').read_text(encoding='utf-8'))
    taken={}
    for e in registry:
        for t,a in e['addresses'].items():taken.setdefault(t,set()).add(int(a,16))
    for target,(filename,digest) in HASHES.items():
        image=(game_dir/filename).read_bytes();assert hashlib.sha256(image).hexdigest()==digest
        pe=pefile.PE(data=image);base=pe.OPTIONAL_HEADER.ImageBase
        data=[(base+s.VirtualAddress,base+s.VirtualAddress+s.Misc_VirtualSize) for s in pe.sections
              if s.Characteristics&0x80000000]  # writable sections
        manifest=json.loads((ROOT/'bfv-native-code/build'/target/'manifest.json').read_text())
        patched=set()
        for p in manifest['entry_patches']:
            start=int(p['entry'],16);patched.update(range(start-4,start+len(p['original'])//2))
        candidates=[]
        with (ROOT/'reports'/target/'all-functions.tsv').open(encoding='utf-8') as f:
            for row in csv.DictReader(f,delimiter='\t'):
                address=int(row['address'],16);size=int(row['bytes'])
                if address in taken.get(target,()):continue
                body=pe.get_data(address-base,size);stores=parse(body)
                if stores:candidates.append((address,stores,body))
        labels=label_targets(ROOT/'bfv-native-code/build'/f'{target}-recomp')
        pointers=absolute_pointers(pe,image,min(c[0] for c in candidates),max(c[0] for c in candidates)+8)
        entries=[];rejected={};lines=['#if BFV_BUILD_'+target.upper(),'']
        for address,stores,body in sorted(candidates):
            interior=set(range(address+1,address+5));reason=None
            if address%16:reason='unaligned_entry'
            elif len(body)<5:reason='short_body'
            elif not all(any(lo<=g and g+w<=hi for lo,hi in data) for g,w,_ in stores):reason='non_writable_target'
            elif interior&patched or address in patched:reason='existing_patch'
            elif interior&labels:reason='interior_branch_target'
            elif interior&pointers:reason='interior_pointer'
            if reason:rejected[reason]=rejected.get(reason,0)+1;continue
            a=f'{address:08x}';symbol=f'bfv_{target}_global_store_{a}'
            entries.append(dict(address=a,symbol=symbol,stores=[[f'{g:08x}',w,f'{v:0{2*w}x}'] for g,w,v in stores],
                guarded_prefix=body[:5].hex(),native_body=body.hex()))
            what=', '.join(f'{g:08x}' for g,_,_ in stores)
            lines+=[f'/* Native {a}; global{"s" if len(stores)>1 else ""} {what}. */',f'void {symbol}(void)','{']
            for g,w,v in stores:
                kind='BfvWord' if w==4 else 'BfvByte'
                lines.append(f'    ((volatile struct {kind} *)0x{g:08x}u)->value = 0x{v:0{2*w}x}u;')
            lines+=['}','']
        source+=[*lines,'#endif','']
        catalog['targets'][target]=dict(original_sha256=digest,rejected=rejected,entries=entries)
        print(target,len(entries),'rejected',rejected)
    destination.write_text('\n'.join(source),encoding='utf-8',newline='\n')
    (ROOT/'bfv-native-code/global-stores.json').write_text(json.dumps(catalog,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--game-dir',type=Path,required=True)
    p.add_argument('--overwrite',action='store_true')
    a=p.parse_args();recover(a.game_dir,a.overwrite)
