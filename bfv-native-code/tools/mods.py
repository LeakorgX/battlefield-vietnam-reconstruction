"""Mods: hooks from mods/<target>/*.c wired into the build (see mods/include/bfv_mod.h).

A hook names a game function by address (`0x00626890`), by its name in
readable/runtime/symbols_<target>.h (`getActiveTemplateAs`) or by its INDEX.tsv
name with `::` written `_` (`Cmd_ObjectTemplate_repairFactor_execute`).

For each hooked function the build generates (build/<target>/mod_hooks.c) an
entry stub with the same trampoline and stack gap as the function's lifted
body and a body that runs the hooks around the lifted body (bfv_mod_run). The
function's detour then jumps to that stub instead of the lifted one; the
lifted body itself is unchanged. Only functions the build detours into C can
be hooked."""
import re
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
import os
MODS = PROJECT / 'mods'
# BFV_MOD_DIR: build the hooks of another folder with <target>/*.c (tests)
SOURCES = Path(os.environ.get('BFV_MOD_DIR', MODS))
FLAGS = ['-m32', '-std=gnu11', '-O2', '-Wall', '-Wextra', '-Wno-unused-parameter', '-ffreestanding', '-fno-builtin',
         '-fno-math-errno', '-msse2', '-mfpmath=sse', '-mstackrealign', '-fno-stack-protector',
         '-fno-asynchronous-unwind-tables', '-fno-unwind-tables', '-fno-tree-loop-distribute-patterns']
HOOK = re.compile(r'\bMOD_(BEFORE|AFTER)\s*\(\s*([A-Za-z_0-9]+)\s*,\s*([A-Za-z_]\w*)\s*\)')


ONLY = None  # build.py --mods: build only these mod files (names without .c)


def sources(target):
    """mods/<target>/*.c, then mods/shared/*.c (built into both executables)."""
    return [p for d in (target, 'shared') if (SOURCES / d).is_dir() for p in sorted((SOURCES / d).glob('*.c'))
            if (ONLY is None and p.stem != 'vulkan') or (ONLY is not None and p.stem in ONLY)]


def strip_comments(text):
    return re.sub(r'//[^\n]*', '', re.sub(r'/\*.*?\*/', ' ', text, flags=re.S))


def names(target, tree):
    """{C name: [addresses]} from the symbols header and INDEX.tsv."""
    found = {}
    header = tree / 'runtime' / f'symbols_{target}.h'
    if header.exists():
        for m in re.finditer(r'^#define (\w+) 0x([0-9a-f]+)$', header.read_text(), re.M):
            found.setdefault(m[1], set()).add(int(m[2], 16))
    index = PROJECT / 'lifted' / target / 'INDEX.tsv'
    files = {}
    if index.exists():
        for line in index.read_text(encoding='utf-8').splitlines()[1:]:
            cols = line.split('\t')
            if len(cols) < 3: continue
            a = int(cols[0], 16); files[a] = cols[1]
            found.setdefault(re.sub(r'[^A-Za-z0-9_]', '_', cols[2].replace('::', '_')), set()).add(a)
    return found, files


def hooks(target, tree):
    """[(kind, address, hook name, source file)] in file order."""
    result = []
    known = None
    for path in sources(target):
        for m in HOOK.finditer(strip_comments(path.read_text(encoding='utf-8'))):
            kind, function, name = m[1].lower(), m[2], m[3]
            if re.fullmatch(r'0x[0-9a-fA-F]+|[0-9a-fA-F]{8}', function):
                address = int(function, 16)
            else:
                if known is None: known, _ = names(target, tree)
                options = sorted(known.get(function, ()))
                if not options: raise RuntimeError(f'{path.name}: {name} hooks unknown function {function} (use its address)')
                if len(options) > 1:
                    raise RuntimeError(f'{path.name}: {function} names several functions ({", ".join(f"{a:08x}" for a in options)}); use the address')
                address = options[0]
            result.append((kind, address, name, path))
    return result


def stack_pops(pe, entry):
    """Bytes the function pops on return, from its ret instructions (-1 when it has none or they differ)."""
    from capstone import Cs, CS_ARCH_X86, CS_MODE_32
    md = Cs(CS_ARCH_X86, CS_MODE_32); md.detail = True
    pops = set()
    for r in entry['ranges']:
        lo, hi = (int(x, 16) for x in r.split('-'))
        for i in md.disasm(pe.get_data(lo - pe.OPTIONAL_HEADER.ImageBase, hi - lo), lo):
            if i.mnemonic == 'ret': pops.add(i.operands[0].imm if i.operands else 0)
    return pops.pop() if len(pops) == 1 else -1


def generate(target, work, tree, pe, catalog):
    """Write work/mod_hooks.c; return ({address: stub symbol}, sources to compile)."""
    found = hooks(target, tree)
    if not found: return {}, []
    by = {int(e['address'], 16): e for e in catalog['entries']}
    _, files = names(target, tree)
    per = {}
    for kind, address, name, path in found:
        if address not in by:
            raise RuntimeError(f'{path.name}: {name} hooks {address:08x}, which is not a lifted function start')
        per.setdefault(address, {'before': [], 'after': []})[kind].append(name)
    lines = ['/* Generated by tools/mods.py from mods/' + target + '/*.c: one entry stub and hook body per hooked function. */',
             '#include "bfv_mod.h"', '']
    stubs = {}
    for address, h in sorted(per.items()):
        e = by[address]; body = f'bfv_{target}_l1_body_{address:08x}'
        stub = f'bfv_mod_{target}_{address:08x}'; modbody = f'bfv_mod_{target}_body_{address:08x}'
        source = tree / target / files.get(address, '')
        text = source.read_text(encoding='utf-8') if source.is_file() else ''
        deep = re.search(r'BFV_L1_ENTRY_DEEP\(bfv_' + target + f'_l1_{address:08x}, \\w+, (0x[0-9a-f]+)\\)', text)
        if not deep and f'BFV_L1_ENTRY(bfv_{target}_l1_{address:08x},' not in text:
            text = next((p.read_text(encoding='utf-8') for p in (tree / target).rglob('*.c')
                         if f'bfv_{target}_l1_{address:08x},' in p.read_text(encoding='utf-8')), '')
            deep = re.search(r'BFV_L1_ENTRY_DEEP\(bfv_' + target + f'_l1_{address:08x}, \\w+, (0x[0-9a-f]+)\\)', text)
        pops = stack_pops(pe, e)
        lines += [f'/* {address:08x}: before {", ".join(h["before"]) or "-"}; after {", ".join(h["after"]) or "-"}; pops {pops} */',
                  f'BFV_L1_ENTRY_DEEP({stub}, {modbody}, {deep[1]});' if deep else f'BFV_L1_ENTRY({stub}, {modbody});',
                  f'void {body}(struct bfv_cpu *c);',
                  *[f'void {n}(struct bfv_mod *mod);' for n in dict.fromkeys(h['before'] + h['after'])],
                  f'void {modbody}(struct bfv_cpu *c)', '{',
                  f'    static const bfv_mod_hook before[] = {{{"".join(n + ", " for n in h["before"])}0}};',
                  f'    static const bfv_mod_hook after[] = {{{"".join(n + ", " for n in h["after"])}0}};',
                  f'    bfv_mod_run(c, 0x{address:08x}u, {pops}, {body}, before, after);', '}', '']
        stubs[address] = stub
    (work / 'mod_hooks.c').write_text('\n'.join(lines), newline='\n')
    backend = sorted((PROJECT / 'vk').glob('*.c')) if target == 'client' and ONLY is not None and 'vulkan' in ONLY else []
    return stubs, [MODS / 'runtime' / 'mod_runtime.c', *sources(target), work / 'mod_hooks.c', *backend]


FIELD = re.compile(r'^#define (\w+) (0x[0-9a-f]+)  /\* field offset \*/$', re.M)


def fields(target):
    """build/<target>/mod_fields.h and mod_slots.h (shared by --output builds), `#define`s for mods:

    - field offsets the readable C names (`#define ObjectTemplate_repairFactor
      0x618` in a method) and the fields notes/<target>/names*.txt names
      (`AISettings+0x8 = maxNBots` -> `AISettings_maxNBots`);
    - virtual method slots tools/slot_names.py names (`VF_Object_update 20`),
      for GAME_VIRTUAL / GAME_METHOD.

    Only names with one value in the whole target; names the symbols header
    already defines are left out. Cached until one of the inputs changes."""
    import slot_names
    readable = PROJECT / 'readable' / target
    out = PROJECT / 'build' / target / 'mod_fields.h'
    out_slots = out.with_name('mod_slots.h')
    out.parent.mkdir(parents=True, exist_ok=True)
    stamp = readable / 'catalog.json'
    if not stamp.exists(): return
    inputs = [stamp, *(PROJECT / 'lifted' / target).glob('*.tsv'), *(PROJECT / 'notes' / target).glob('names*.txt'),
              Path(slot_names.__file__), Path(__file__)]
    newest = max(p.stat().st_mtime for p in inputs)
    if all(p.exists() and p.stat().st_mtime >= newest for p in (out, out_slots)): return
    seen = {}
    for path in sorted(readable.rglob('*.c')):
        for m in FIELD.finditer(path.read_text(encoding='utf-8')):
            seen.setdefault(m[1], set()).add(int(m[2], 16))
    cn = slot_names.ClassNames(target)
    for (cls, off), (name, _, _) in cn.fields.items():
        seen.setdefault(f'{cls}_{name}', set()).add(off)
    header = PROJECT / 'readable' / 'runtime' / f'symbols_{target}.h'
    taken = set(re.findall(r'^#define (\w+) ', header.read_text(), re.M)) if header.exists() else set()
    unique = {n: v.pop() for n, v in sorted(seen.items()) if len(v) == 1 and n not in taken}
    lines = [f'/* Generated by tools/mods.py: {len(unique)} {target} field offsets named in readable/{target}/ '
             f'and notes/{target}/names*.txt */',
             f'#ifndef BFV_MOD_FIELDS_{target.upper()}_H', f'#define BFV_MOD_FIELDS_{target.upper()}_H',
             *[f'#define {n} 0x{v:x}' for n, v in unique.items()], '#endif', '']
    out.write_text('\n'.join(lines), newline='\n')
    slots = {}
    for cls, (_, n, _) in cn.classes.items():
        for k in range(n):
            if (s := cn.slot(cls, k)):
                slots.setdefault(f'VF_{slot_names.short(cls)}_{s[0]}', set()).add(k)
    unique = {n: v.pop() for n, v in sorted(slots.items()) if len(v) == 1 and n not in taken}
    lines = [f'/* Generated by tools/mods.py: {len(unique)} {target} virtual method slots (tools/slot_names.py).',
             ' * GAME_METHOD(obj, Object, update) is the function in slot VF_Object_update of the object.',
             ' * Left out: names a class uses for two slots (overloads) or two classes of one name. */',
             f'#ifndef BFV_MOD_SLOTS_{target.upper()}_H', f'#define BFV_MOD_SLOTS_{target.upper()}_H',
             *[f'#define {n} {v}' for n, v in unique.items()], '#endif', '']
    out_slots.write_text('\n'.join(lines), newline='\n')


def compile(target, work, tree, files, run, gcc):
    """Compile the mod sources; return the objects."""
    out = work / 'mods'; out.mkdir(parents=True, exist_ok=True)
    log = re.search(r'^#define imp_OutputDebugStringA (0x[0-9a-f]+)$', (tree / 'runtime' / f'symbols_{target}.h').read_text(), re.M)
    fields(target)
    objects = []
    for f in files:
        o = out / (('' if f.parent.name == target or f.parent == work else f.parent.name + '_') + f.stem + '.o')
        run([gcc, *FLAGS, f'-DBFV_MOD_{target.upper()}', f'-DBFV_MOD_LOG_IMPORT={log[1]}u', '-I', MODS / 'include', '-I', tree / 'runtime', '-I', PROJECT / 'build' / target, '-c', f, '-o', o], work)
        objects.append(o)
    return objects
