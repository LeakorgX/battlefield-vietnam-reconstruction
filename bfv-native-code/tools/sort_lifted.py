"""Sort the L1 lifted C into the game's own source layout.

Every lifted function gets a home (folder and file) from evidence in the
executable:

1. *source path*: the function references one of the developers' own source
   paths (assert strings like ``c:\\bfv_code\\main\\battlefield\\AIBotActionPlan\\BAPConOr.cpp``);
2. *virtual method*: it sits in a class's vtable (MSVC RTTI names the class and
   its namespaces, e.g. ``dice::bf::ai::EntryPlaneRoll``); a method shared by
   several vtables goes to the class with the fewest bases;
3. *vtable store*: it writes exactly one class's vtable (constructor/destructor);
   *library strings / library run*: a statically linked library's own messages
   mark its code (``lib/``); the game pads functions to 16 bytes and the
   libraries do not, so unpadded neighbours of library code join it;
4. *between same file / same folder*: MSVC keeps each object file's code
   together, so unknown functions between two anchors of one file (folder) go
   to that file (to ``misc.c`` of that folder);
5. everything else goes to ``unsorted/`` in address order.

Only whole function texts move. Each text is checked against its catalog
c_sha256 (the hash its verification is tied to) before anything is written, so
verification carries over unchanged. A comment above each function gives its
address, class, evidence and the strings it references; comments are outside
the hashed text.

Writes ``lifted/<target>/<folder>/<File>.c`` and ``lifted/<target>/INDEX.tsv``.
"""
